it('fallback directory includes both organization capabilities without granting them to builtin templates', () => {
  expect(defaultPermissions.filter(item => item.key.startsWith('organizations:')).map(item => item.key)).toEqual(['organizations:read', 'organizations:write'])
  for (const role of defaultRoleTemplates) {
    expect(role.permissions.some(key => key.startsWith('organizations:'))).toBe(false)
  }
  for (const role of config.rbac.roles) {
    expect(role.permissions.some(key => key.startsWith('organizations:'))).toBe(false)
  }
})

